#!/usr/bin/env python3
"""Build the install plan from checked boxes without installing anything."""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
p = root / 'CHECKLIST.md'
text = re.sub(r'\[\s*[xX]\s*\]', '[x]', p.read_text())
p.write_text(text)
selected = []
section = ''
for line in text.splitlines():
    if line.startswith('## '):
        section = line[3:]
    if line.startswith('- [x] '):
        selected.append({'section': section, 'item': line[6:]})

app_casks = {
    'Ardia': 'ardia', 'ArtCraft Launcher': 'artcraft-launcher',
    'Blip': 'blip', 'ChatGPT': 'chatgpt', 'CleanShot X': 'cleanshot',
    'DisplayLink Manager': 'displaylink', 'Ghostty': 'ghostty',
    'Grok Bot': 'grok-bot', 'Jump Desktop': 'jump-desktop', 'Parsec': 'parsec',
    'Presentify': 'presentify', 'Raycast': 'raycast', 'Tailscale': 'tailscale-app',
    'Notchy': 'vishvavariya/notchy/notchy',
}
direct_catalog = json.loads((root / 'manifests/direct-apps.json').read_text())
direct_by_name = {app['name']: app for app in direct_catalog}
formulas, casks = set(), set()
manual, direct, mas = [], [], {}
for choice in selected:
    item, section = choice['item'], choice['section']
    if section == 'Applications found':
        name = re.search(r'\*\*(.+?)\*\*', item).group(1)
        if name in app_casks:
            casks.add(app_casks[name])
        elif name in direct_by_name:
            direct.append(direct_by_name[name])
        elif name == 'Magnet':
            mas[name] = 441258766
            formulas.add('mas')  # Helper for the selected Mac App Store app.
        else:
            manual.append(name)
    elif section == 'Homebrew casks':
        casks.add(re.search(r'`([^`]+)`', item).group(1))
    elif section.startswith('Homebrew formulae') or section == 'Other installed Homebrew formulae':
        formulas.add(re.search(r'`([^`]+)`', item).group(1))
    elif item == 'Git and GitHub CLI, then sign in again':
        formulas.update(['git', 'gh'])

assert all(re.fullmatch(r'[A-Za-z0-9@+_./-]+', n) for n in formulas | casks)
brewfile = ['# Generated by scripts/prepare.py from CHECKLIST.md.',
            '# Re-run preparation after changing your selections.']
brewfile += [f'brew "{n}"' for n in sorted(formulas)]
brewfile += [f'cask "{n}"' for n in sorted(casks)]
brewfile += [f'mas "{name}", id: {app_id}' for name, app_id in sorted(mas.items())]
(root / 'Brewfile.selected').write_text('\n'.join(brewfile) + '\n')
fields = ['name', 'bundle', 'version', 'type', 'url', 'sha256', 'arch']
tsv = ['# name\tbundle\tversion\ttype\turl\tsha256\tarch']
for app in direct:
    assert re.fullmatch(r'[a-f0-9]{64}', app['sha256']), app['name']
    assert all('\t' not in str(app[f]) and '\n' not in str(app[f]) for f in fields)
    tsv.append('\t'.join(app[f] for f in fields))
(root / 'manifests/direct-selected.tsv').write_text('\n'.join(tsv) + '\n')
(root / 'inventory/selected.json').write_text(json.dumps({
    'checked_items': selected, 'formulae': sorted(formulas), 'casks': sorted(casks),
    'direct_apps': [app['name'] for app in direct], 'mac_app_store': mas,
    'manual_apps': manual,
}, indent=2) + '\n')
lines = ['# Account and first-launch setup', '',
         'All currently selected apps have an installation route. The command reports failures and can be rerun.', '',
         '## Steps requiring your involvement', '',
         '- Sign into the Mac App Store with the Apple Account that owns Magnet before running setup. If not owned, purchase Magnet in the App Store first. The installer does not buy it.',
         '- Approve macOS installer/password prompts and first-launch permissions, including DisplayLink and Accessibility access as needed.',
         '- Sign into GitHub and your apps; activate purchased licenses.',
         '- Finish browser bookmarks, Keychain, and iCloud sync.',
         '- Configure and verify backups and FileVault.',
         '- Isocast may request its codec download on first launch.',
         '- Shell preferences, font, and editor were selected as broad goals; no specific settings files, font, editor app, or extensions were individually selected.',
         '- The selected `codex` cask is the CLI, not the desktop app.',
         '- No settings contents, licenses, passwords, or private files are included.',
         '', '## Download sources', '', 'See [SOURCES.md](SOURCES.md) for the verified official sources.', '']
if manual:
    lines += ['## Selected apps without automation', ''] + [f'- [ ] {name}' for name in manual]
(root / 'MANUAL-INSTALL.md').write_text('\n'.join(lines))
print(f'Prepared {len(formulas)} formulae, {len(casks)} casks, {len(direct)} direct apps, {len(mas)} App Store app(s), {len(manual)} unresolved apps.')
